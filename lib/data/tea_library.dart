class TeaLibrary {
  TeaLibrary._();

  /// 合并后的茶库：《中国茶图鉴》298 款为准，手写库里书里没有的条目一并保留。
  static final List<Tea> all = _merge();

  /// 书里收录的款数。
  static final int bookCount = parseBookSeed().length;

  static final Map<String, int> categoryCounts = _buildCounts();

  static final List<String> categories = _buildCategories();

  static final List<String> origins = _buildOrigins();

  static final Map<String, String> images = <String, String>{
    'ol-dahongpao': 'assets/library/hero/tea_dahongpao.webp',
    'bl-silver': 'assets/library/hero/tea_silverneedle.webp',
    'lv-longjing': 'assets/library/hero/tea_longjing.webp',
    'lv-maojian': 'assets/library/hero/tea_maojian.webp',
  };

  static final Map<String, Tea> byId = <String, Tea>{
    for (final tea in all) tea.id: tea,
  };

  static Tea get featured => byId['ol-dahongpao'] ?? all.first;

  static Tea? find(String? id) => id == null ? null : byId[id];

  static List<Tea> _merge() {
    final book = parseBookSeed();
    final handwritten = _parse();
    final bookNames = book.map((t) => t.name).toSet();
    return <Tea>[
      ...book,
      ...handwritten.where((t) => !bookNames.contains(t.name)),
    ];
  }

  static List<String> _buildCategories() {
    const order = <String>[
      '绿茶',
      '红茶',
      '乌龙茶',
      '白茶',
      '黑茶',
      '普洱茶',
      '黄茶',
      '花茶',
      '非茶之茶',
    ];
    final present = all.map((t) => t.category).toSet().toList();
    present.sort((a, b) {
      final ia = order.indexOf(a);
      final ib = order.indexOf(b);
      return (ia < 0 ? 99 : ia).compareTo(ib < 0 ? 99 : ib);
    });
    return present;
  }

  static Map<String, int> _buildCounts() {
    final counts = <String, int>{};
    for (final tea in all) {
      counts[tea.category] = (counts[tea.category] ?? 0) + 1;
    }
    return counts;
  }

  static List<String> _buildOrigins() {
    final provinces = <String>{};
    for (final tea in all) {
      final parts = tea.origin.split('·');
      if (parts.isNotEmpty && parts.first.isNotEmpty) provinces.add(parts.first);
    }
    final list = provinces.toList()..sort();
    return list;
  }

  static List<Tea> _parse() {
    final result = <Tea>[];
    for (final line in _seed.split('\n')) {
      final row = line.trim();
      if (row.isEmpty) continue;
      final cells = row.split('|');
      if (cells.length < 13) continue;
      final steeps = cells[9]
          .split(',')
          .map((e) => int.tryParse(e.trim()) ?? 0)
          .where((e) => e > 0)
          .toList();
      final id = cells[0];
      result.add(
        Tea(
          id: id,
          name: cells[1],
          category: cells[2],
          origin: cells[3],
          flavor: cells[4],
          aroma: cells[5],
          brewTemp: int.tryParse(cells[6]) ?? 90,
          ratio: cells[7],
          vessel: cells[8],
          steeps: steeps.isEmpty ? <int>[20, 25, 30] : steeps,
          summary: cells[10],
          story: cells[11],
          source: cells[12],
          image: images[id],
        ),
      );
    }
    return result;
  }
}

/// 城市 / 产地过滤用的归一化比较。
String normalizeOrigin(String origin) {
  final parts = origin.split('·');
  return parts.first.replaceAll(RegExp(r'[省市自治区]'), '').trim();
}

int shuffleCount(int length) => min(length, 3);
